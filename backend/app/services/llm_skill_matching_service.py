# ==============================================================================
# LLM SKILL MATCHING SERVICE
# ==============================================================================


class LLMSkillMatchingService:
    """
    Evaluates required skills matching between:

        JobDescription.required_skills
                     ↕
              Resume.skills

    Uses the existing local Qwen3 8B model via Ollama in a single compact
    prompt per resume.

    Python validates LLM outputs, enforces strict anti-hallucination bounds,
    and computes matched / unmatched counts.
    """

    def build_prompt(
        self,
        required_skills: list[str],
        resume_skills: list[str],
    ) -> str:
        """
        Build the prompt sent to Qwen3 8B for evaluating all required skills
        in a single request.
        """
        return f"""You are TalentAI's Specialized Skill Equivalence Evaluator.

Your ONLY task is to determine whether each required skill from a Job Description (JD) is satisfied by an equivalent skill in the candidate's Resume Skills list.

==================================================
JOB DESCRIPTION REQUIRED SKILLS
==================================================
{json.dumps(required_skills, indent=2)}

==================================================
CANDIDATE RESUME SKILLS
==================================================
{json.dumps(resume_skills, indent=2)}

==================================================
EVALUATION RULES
==================================================
1. EVALUATE EVERY JD SKILL INDEPENDENTLY:
   Provide exactly one decision for EVERY required skill in the JD list, preserving the exact required_skill text.

2. MATCH EQUIVALENT SKILLS REGARDLESS OF WORDING OR ABBREVIATIONS:
   Mark matched=true when a resume skill represents the same technology, tool, methodology, or competency under a different synonym, alternate spelling, acronym, or abbreviation.
   Examples of valid equivalents:
   - "Kubernetes" <=> "k8s"
   - "PostgreSQL" <=> "Postgres"
   - "Amazon Web Services" <=> "AWS"
   - "Node.js" <=> "NodeJS" or "Node js"
   - "Golang" <=> "Go"
   - "Scikit-Learn" <=> "sklearn"
   - "Electrocardiogram" <=> "ECG" or "EKG"
   - "Heating, Ventilation, and Air Conditioning" <=> "HVAC"
   - "Programmable Logic Controllers" <=> "PLC"
   - "Computer-Aided Design" <=> "CAD"
   - "Financial Modeling" <=> "DCF modeling"

3. REJECT RELATED BUT NON-EQUIVALENT SKILLS:
   Do NOT match skills that are merely in the same domain, ecosystem, or category unless they are genuinely interchangeable.
   Examples of INVALID matches (must be matched=false, resume_skill=null):
   - "AWS" vs "Pandas" (cloud infrastructure vs python library -> REJECT)
   - "Docker" vs "Kubernetes" (container runtime vs orchestrator -> REJECT)
   - "Java" vs "JavaScript" (distinct programming languages -> REJECT)
   - "Python" vs "C++" (distinct programming languages -> REJECT)
   - "SQL" vs "NoSQL" (relational vs non-relational database -> REJECT)
   - "Machine Learning" vs "Deep Learning" (general field vs neural net subset -> REJECT)
   - "AutoCAD" vs "Revit" (2D drafting vs BIM -> REJECT)
   - "Cardiology" vs "Neurology" (distinct medical specialties -> REJECT)
   - "HVAC" vs "Plumbing" (distinct building services -> REJECT)

4. REJECT MATCHES BASED SOLELY ON A LIBRARY'S POSSIBLE CAPABILITIES:
   Do NOT match a required skill to a tool, library, framework, or algorithm based solely on what that tool might be capable of doing, unless the candidate explicitly provides direct evidence of the required skill.
   Examples of INVALID capability-based matches (must be matched=false, resume_skill=null):
   - "CNN" / "Convolutional Neural Networks" vs "TensorFlow", "Keras", or "PyTorch" (general DL framework does NOT prove CNN expertise -> REJECT)
   - "LSTM" / "Long Short-Term Memory" / "RNN" vs "Keras", "TensorFlow", or "PyTorch" (general DL API does NOT prove sequence modeling expertise -> REJECT)
   - "Model Deployment" vs "Flask", "Django", or "FastAPI" (general web framework does NOT prove ML model deployment expertise -> REJECT)
   - "Unsupervised Learning" vs "K-Means" (a single algorithm does NOT qualify for the entire discipline of unsupervised learning -> REJECT)
   - "Deep Learning" vs "Python" (general programming language does NOT prove deep learning competency -> REJECT)
   - "Computer Vision" vs "Python", "C++", or "Pandas" (general language/library does NOT prove computer vision competency -> REJECT; OpenCV or explicit CV required)
   - "NLP" / "Natural Language Processing" vs "Python", "Pandas", or "Java" (general language/library does NOT prove NLP competency -> REJECT; NLTK, spaCy, or explicit NLP required)

5. NEVER INVENT SKILLS (NO HALLUCINATIONS):
   When matched=true, "resume_skill" MUST be an exact string chosen from the CANDIDATE RESUME SKILLS list provided above.
   Do not invent, synthesize, or infer resume skills that are not explicitly present in the list.

6. INSUFFICIENT EVIDENCE:
   If no candidate resume skill is genuinely equivalent to the required skill, set matched=false and resume_skill=null.

==================================================
OUTPUT FORMAT
==================================================
Return ONLY valid JSON matching the requested schema.
"""

    def _build_fallback_unmatched_result(
        self,
        required_skills: list[str],
        status: str = "completed",
        error: str | None = None,
    ) -> dict[str, Any]:
        """
        Build an unmatched result where all requirements are unmatched.
        Used on empty resume skills (status="completed", error=None)
        or on LLM failure / timeout (status="failed", error=...).
        """
        total = len(required_skills)
        matches = [
            {
                "required_skill": skill,
                "matched": False,
                "resume_skill": None,
                "match_type": None,
                "similarity": None,
                "retrieved_skill": None,
            }
            for skill in required_skills
        ]
        res: dict[str, Any] = {
            "total_required_skills": total,
            "matched_required_skills": 0,
            "unmatched_required_skills": total,
            "matches": matches,
            "status": status,
        }
        if error is not None:
            res["error"] = error
        return res

    async def match_required_skills(
        self,
        job_description: JobDescriptionObject,
        resume: ResumeObject,
    ) -> dict[str, Any]:
        """
        Match JD required skills against candidate Resume skills using Qwen3 8B.

        Guarantees:
        - Sends exactly one LLM request for the entire resume skills matching.
        - Python independently validates decisions and prevents hallucinations.
        - Calculates total_required_skills, matched_required_skills, and
          unmatched_required_skills.
        - Preserves response structure expected by ExactMatchingResult.
        - Distinguishes valid empty evidence / 0 matches from LLM service failures.
        """
        required_skills = [
            skill.strip()
            for skill in job_description.required_skills
            if skill and skill.strip()
        ]

        resume_skills = [
            skill.strip()
            for skill in resume.skills
            if skill and skill.strip()
        ]

        total_required = len(required_skills)

        # -------------------------------------------------------------
        # Edge cases: empty requirements or empty resume skills
        # -------------------------------------------------------------
        if total_required == 0:
            return {
                "total_required_skills": 0,
                "matched_required_skills": 0,
                "unmatched_required_skills": 0,
                "matches": [],
                "status": "completed",
            }

        if len(resume_skills) == 0:
            return self._build_fallback_unmatched_result(
                required_skills,
                status="completed",
                error=None,
            )

        # Lookup map for case-insensitive resolution to original candidate string
        resume_skills_lookup: dict[str, str] = {
            s.strip().lower(): s.strip()
            for s in resume_skills
        }

        # -------------------------------------------------------------
        # Build prompt & call Qwen3 8B (exactly one call per resume)
        # -------------------------------------------------------------
        prompt = self.build_prompt(
            required_skills=required_skills,
            resume_skills=resume_skills,
        )

        try:
            raw_response = await llm_service.generate_json(
                prompt=prompt,
                schema=LLMSkillMatchingOutput,
            )
            validated_output = LLMSkillMatchingOutput.model_validate(
                raw_response
            )

            # -------------------------------------------------------------
            # Python Validation & Anti-Hallucination Guard
            # -------------------------------------------------------------
            decisions_by_skill: dict[str, SingleSkillDecision] = {}
            for decision in validated_output.skill_decisions:
                norm_key = decision.required_skill.strip().lower()
                if norm_key not in decisions_by_skill:
                    decisions_by_skill[norm_key] = decision

            matches = []
            matched_count = 0

            for req_skill in required_skills:
                norm_req = req_skill.strip().lower()
                decision = decisions_by_skill.get(norm_req)

                is_matched = False
                verified_resume_skill: str | None = None
                candidate_retrieved_skill: str | None = None

                if decision is not None:
                    candidate_retrieved_skill = decision.resume_skill

                    if decision.matched and decision.resume_skill:
                        candidate_clean = decision.resume_skill.strip()
                        norm_candidate = candidate_clean.lower()

                        # Strict anti-hallucination verification:
                        # resume_skill MUST exist in the candidate's actual resume skills!
                        if norm_candidate in resume_skills_lookup:
                            if (norm_req, norm_candidate) in DISALLOWED_CAPABILITY_MAPPINGS:
                                logger.warning(
                                    "Rejected capability-based skill match '%s' for requirement '%s' "
                                    "(library capability does not substitute for required skill)",
                                    decision.resume_skill,
                                    req_skill,
                                )
                                is_matched = False
                                verified_resume_skill = None
                            else:
                                verified_resume_skill = resume_skills_lookup[
                                    norm_candidate
                                ]
                                is_matched = True
                        else:
                            logger.warning(
                                "Rejected hallucinated resume skill '%s' for requirement '%s' "
                                "(not present in candidate resume.skills)",
                                decision.resume_skill,
                                req_skill,
                            )
                            is_matched = False
                            verified_resume_skill = None

                if is_matched:
                    matched_count += 1
                    matches.append(
                        {
                            "required_skill": req_skill,
                            "matched": True,
                            "resume_skill": verified_resume_skill,
                            "match_type": "llm",
                            "similarity": 1.0,
                            "retrieved_skill": verified_resume_skill,
                        }
                    )
                else:
                    matches.append(
                        {
                            "required_skill": req_skill,
                            "matched": False,
                            "resume_skill": None,
                            "match_type": None,
                            "similarity": None,
                            "retrieved_skill": candidate_retrieved_skill,
                        }
                    )

            unmatched_count = total_required - matched_count

            # Internal count consistency verification:
            # Guarantees mathematical agreement between matched_count and matches list
            computed_matched = sum(1 for m in matches if m["matched"] is True)
            assert matched_count == computed_matched, (
                f"Internal count mismatch: matched_count={matched_count} vs matches={computed_matched}"
            )
            assert total_required == matched_count + unmatched_count, (
                f"Internal count mismatch: total={total_required} vs {matched_count}+{unmatched_count}"
            )

            return {
                "total_required_skills": total_required,
                "matched_required_skills": matched_count,
                "unmatched_required_skills": unmatched_count,
                "matches": matches,
                "status": "completed",
            }
        except Exception as exc:
            err_msg = f"LLM skill matching failed: {exc}"
            logger.error(
                "%s. Returning failed fallback.",
                err_msg,
            )
            return self._build_fallback_unmatched_result(
                required_skills,
                status="failed",
                error=err_msg,
            )


llm_skill_matching_service = LLMSkillMatchingService()
