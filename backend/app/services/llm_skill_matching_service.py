class SingleSkillDecision(BaseModel):
    """
    LLM evaluation decision for a single JD required skill.
    """

    model_config = ConfigDict(
        str_strip_whitespace=True,
        extra="forbid",
    )

    required_skill: str = Field(
        description="The exact required skill string from the Job Description."
    )
    matched: bool = Field(
        description="True if an equivalent skill is present in the candidate resume skills list, False otherwise."
    )
    resume_skill: str | None = Field(
        default=None,
        description="The exact matching skill string from the candidate resume skills list if matched, or null."
    )
    reason: str = Field(
        default="",
        description="Brief explanation of why the skill matched or why no candidate skill qualifies."
    )


class LLMSkillMatchingOutput(BaseModel):
    """
    Container for all skill matching decisions generated by the LLM in one request.
    """

    model_config = ConfigDict(
        str_strip_whitespace=True,
        extra="forbid",
    )

    skill_decisions: list[SingleSkillDecision] = Field(
        default_factory=list,
        description="One evaluation decision for each required skill from the Job Description."
    )


